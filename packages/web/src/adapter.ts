import type { Database } from "@shopping-assistant/database";
import {
  createAdapterFactory,
  type CleanedWhere,
  type CustomAdapter,
  type DBTransactionAdapter,
} from "better-auth/adapters";

type Row = Record<string, unknown>;

/**
 * Knex's fluent types narrow on every call, which makes them unusable for a
 * generic table adapter. The queries below are all plain selects and writes on
 * one table, so they are typed by their result instead.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Builder = any;

/**
 * Translates one Better Auth `where` entry into the query builder. Case
 * insensitivity is per-value, so it is applied per condition rather than to
 * the whole statement.
 */
function applyWhere(query: Builder, where: CleanedWhere): Builder {
  const insensitive = where.mode === "insensitive" && typeof where.value === "string";
  const column = insensitive ? query.client.raw("lower(??)", [where.field]) : where.field;
  const value = insensitive ? (where.value as string).toLowerCase() : where.value;

  switch (where.operator) {
    case "ne":
      return query.whereNot(column, value);
    case "lt":
      return query.where(column, "<", value);
    case "lte":
      return query.where(column, "<=", value);
    case "gt":
      return query.where(column, ">", value);
    case "gte":
      return query.where(column, ">=", value);
    case "in":
      return query.whereIn(column, value as unknown[]);
    case "not_in":
      return query.whereNotIn(column, value as unknown[]);
    case "contains":
      return query.where(column, "like", `%${String(value)}%`);
    case "starts_with":
      return query.where(column, "like", `${String(value)}%`);
    case "ends_with":
      return query.where(column, "like", `%${String(value)}`);
    default:
      return query.where(column, value);
  }
}

/**
 * Better Auth's core queries join their conditions with AND. An OR would need
 * grouped predicates, which knex cannot express without raw SQL, so it fails
 * loudly rather than quietly returning the wrong rows.
 */
function applyWheres(query: Builder, where: CleanedWhere[]): Builder {
  for (const entry of where) {
    if (entry.connector === "OR") {
      throw new Error("The knex adapter does not support OR-joined where clauses");
    }
  }
  return where.reduce(applyWhere, query);
}

function createCustomAdapter(connection: Database): CustomAdapter {
  const table = (model: string): Builder => connection(model);

  return {
    async create({ model, data, select }) {
      const rows = await table(model)
        .insert(data as Row)
        .returning(select ?? "*");
      return rows[0] as never;
    },

    async findOne({ model, where, select }) {
      const row = await applyWheres(table(model), where).first(select ?? "*");
      return (row as never) ?? null;
    },

    async findMany({ model, where, limit, select, sortBy, offset }) {
      let query = where ? applyWheres(table(model), where) : table(model);
      query = select && select.length > 0 ? query.select(select) : query.select("*");
      if (sortBy) query = query.orderBy(sortBy.field, sortBy.direction);
      if (offset) query = query.offset(offset);
      if (limit) query = query.limit(limit);
      return (await query) as never;
    },

    async count({ model, where }) {
      const query = where ? applyWheres(table(model), where) : table(model);
      const rows = await query.count({ count: "*" });
      return Number((rows[0] as { count?: string } | undefined)?.count ?? 0);
    },

    async update({ model, where, update }) {
      const rows = await applyWheres(table(model), where)
        .update(update as Row)
        .returning("*");
      return (rows[0] as never) ?? null;
    },

    async updateMany({ model, where, update }) {
      return applyWheres(table(model), where).update(update as Row);
    },

    async delete({ model, where }) {
      await applyWheres(table(model), where).del();
    },

    async deleteMany({ model, where }) {
      return applyWheres(table(model), where).del();
    },
  };
}

/**
 * Better Auth over the installation's existing knex connection. The project has
 * one query builder and one migration story, so a second ORM (Kysely) would
 * mean a second pool and a schema applied outside knex's rollbacks.
 */
export function createKnexAdapter(database: Database) {
  return createAdapterFactory({
    config: {
      adapterId: "knex",
      adapterName: "Knex",
      // Ids are opaque text generated by Better Auth, never by the database.
      supportsUUIDs: false,
      supportsDates: true,
      supportsBooleans: true,
      supportsJSON: true,
      transaction: async (callback) =>
        database.transaction(async (transaction) =>
          callback({
            id: "knex-transaction",
            ...createCustomAdapter(transaction as Database),
          } as unknown as DBTransactionAdapter),
        ),
    },
    adapter: () => createCustomAdapter(database),
  });
}
